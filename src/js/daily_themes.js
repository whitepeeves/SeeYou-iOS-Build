function getSpainNow() {
    const parts = new Intl.DateTimeFormat("en-US", {
        timeZone: "Europe/Madrid",
        year: "numeric",
        month: "2-digit",
        day: "2-digit",
        hour: "2-digit",
        minute: "2-digit",
        second: "2-digit",
        hour12: false
    }).formatToParts(new Date());
    const dateParts = {};
    parts.forEach(p => { if (p.type !== "literal") dateParts[p.type] = p.value; });
    return new Date(Date.UTC(
        Number(dateParts.year),
        Number(dateParts.month) - 1,
        Number(dateParts.day),
        Number(dateParts.hour),
        Number(dateParts.minute),
        Number(dateParts.second)
    ));
}

function getSpainDayKey(date = null) {
    const now = date ? new Date(date) : getSpainNow();
    const parts = new Intl.DateTimeFormat("en-GB", {
        timeZone: "Europe/Madrid",
        year: "numeric",
        month: "2-digit",
        day: "2-digit"
    }).formatToParts(now);
    const dateParts = {};
    parts.forEach(p => { if (p.type !== "literal") dateParts[p.type] = p.value; });
    return `${dateParts.year}-${dateParts.month}-${dateParts.day}`;
}

// El tema del día (y la racha) cambian a las 10:00 hora de Madrid, no a medianoche.
const DAILY_THEME_ROLLOVER_HOUR = 10;
function getThemeDayKey(date = null) {
    const when = date ? new Date(date) : new Date();
    if (Number.isNaN(when.getTime())) return getSpainDayKey();
    const parts = {};
    new Intl.DateTimeFormat("en-GB", { timeZone: "Europe/Madrid", year: "numeric", month: "2-digit", day: "2-digit", hour: "2-digit", hourCycle: "h23" })
        .formatToParts(when).forEach(p => { if (p.type !== "literal") parts[p.type] = Number(p.value); });
    const shifted = new Date(Date.UTC(parts.year, parts.month - 1, parts.day, (parts.hour % 24) - DAILY_THEME_ROLLOVER_HOUR));
    return `${shifted.getUTCFullYear()}-${String(shifted.getUTCMonth() + 1).padStart(2, "0")}-${String(shifted.getUTCDate()).padStart(2, "0")}`;
}

function getSpainLocalHour(date = null) {
    const now = date ? new Date(date) : new Date();
    const parts = new Intl.DateTimeFormat("en-US", {
        timeZone: "Europe/Madrid",
        hour: "2-digit",
        minute: "2-digit",
        second: "2-digit",
        hour12: false
    }).formatToParts(now);
    const dateParts = {};
    parts.forEach(p => { if (p.type !== "literal") dateParts[p.type] = p.value; });
    return Number(dateParts.hour) + Number(dateParts.minute) / 60 + Number(dateParts.second) / 3600;
}

