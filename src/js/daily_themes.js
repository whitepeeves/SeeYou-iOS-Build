function getDailyThemeForDate(spainDate = null) {
    const key = getThemeDayKey(spainDate);
    const [year, month, day] = key.split("-").map(Number);
    // Calendario en UTC: con horas locales, el cambio de hora de verano restaba 1 h y el "floor" daba un dia menos (tema desfasado de marzo a octubre).
    const [startYear, startMonth, startDay] = String(DAILY_THEME_START_DATE).split("-").map(Number);
    const start = Date.UTC(startYear, startMonth - 1, startDay);
    const current = Date.UTC(year, month - 1, day);
    const diff = Math.round((current - start) / (1000 * 60 * 60 * 24));
    let dayIndex = diff >= 0 ? diff : 0;
    // Ultimo reinicio que ya ha empezado (si lo hay): desde ahi se cuenta de 0 y con los temas barajados.
    let reset = null;
    for (let i = 0; i < DAILY_THEME_RESETS.length; i++) { if (DAILY_THEME_RESETS[i].date <= key) reset = DAILY_THEME_RESETS[i]; }
    // Desde DAILY_THEME_NEW_FROM empieza la tanda nueva (sin barajar) salvo que un reinicio mas reciente la sustituya.
    if (!reset && key >= DAILY_THEME_NEW_FROM) reset = { date: DAILY_THEME_NEW_FROM, seed: 0 };
    // Temas extra: ese dia sale el tema puesto a mano; los dias posteriores se desplazan uno por cada tema extra anterior (dentro del mismo reinicio).
    let shift = 0;
    for (let i = 0; i < DAILY_THEME_INSERTS.length; i++) {
        const ins = DAILY_THEME_INSERTS[i];
        if (ins.date === key) {
            return { index: getCustomThemeIndex(ins.text), theme: ins.text, category: "actualidad", categoryIndex: 0, categoryCount: 1, custom: true };
        }
        if (ins.date < key && (!reset || ins.date >= reset.date)) shift++;
    }
    if (reset) {
        const [ry, rm, rd] = reset.date.split("-").map(Number);
        const sinceReset = Math.max(0, Math.round((current - Date.UTC(ry, rm - 1, rd)) / (1000 * 60 * 60 * 24)) - shift);
        const order = reset.seed ? getShuffledThemeOrder(reset.seed) : DAILY_THEME_NEW_ORDER;
        const pos = sinceReset % order.length;
        const item = DAILY_THEME_PROMPTS[order[pos]];
        return { index: order[pos], theme: item.text, category: item.category, categoryIndex: pos, categoryCount: order.length };
    }
    dayIndex = Math.max(0, dayIndex - shift);
    const category = DAILY_THEME_CATEGORIES[dayIndex % DAILY_THEME_CATEGORIES.length];
    const prompts = DAILY_THEMES_BY_CATEGORY[category] || [];
    if (!prompts.length) return null;
    const categoryIndex = Math.floor(dayIndex / DAILY_THEME_CATEGORIES.length) % prompts.length;
    const selected = prompts[categoryIndex];
    return {
        index: selected.globalIndex,
        theme: selected.text,
        category: selected.category,
        categoryIndex,
        categoryCount: prompts.length
    };
}

